export const directPortPaths = directPortModules.flatMap<SourceLeafPath>(({ leaves }) => leaves);

export type SourcePortStatus =
  | { readonly kind: "pending"; readonly source: SourcePortRow }
  | { readonly kind: "direct-unmounted"; readonly source: SourcePortRow; readonly module: string };

export function getSourcePortStatus(path: SourceLeafPath): SourcePortStatus {
  const source = sourcePortRows.find(([sourcePath]) => sourcePath === path);
  if (!source) throw new Error(`Unknown source leaf: ${path}`);
  const direct = directPortModules.find(({ leaves }) => leaves.some((sourcePath) => sourcePath === path));
  return direct ? { kind: "direct-unmounted", source, module: direct.module } : { kind: "pending", source };
}
